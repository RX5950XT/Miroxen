// 執行：npx --package @playwright/cli playwright-cli -s=miroxen-ui run-code --filename tests/dashboard_check.js
async (page) => {
  let checks = 0;
  const errors = [], onError = (error) => errors.push(error.message);
  page.on("pageerror", onError);
  const check = (condition, message) => { if (!condition) throw new Error(message); checks++; };
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.reload();
  await page.waitForFunction(() => state.models.length === 2 && state.loraRows.length >= 6);
  await page.locator("#prompt").fill("一隻紅熊貓");
  const png = Buffer.from(await page.evaluate(() => { const c = document.createElement("canvas"); c.width = c.height = 256; c.getContext("2d").fillRect(0, 0, 256, 256); return c.toDataURL("image/png").split(",")[1]; }), "base64");
  const fixture = { name: "reference.png", mimeType: "image/png", buffer: png };
  check(await page.locator("#loras input[type=checkbox]").count() === 3, "圖片 LoRA 篩選");
  await page.getByRole("checkbox", { name: /viggle-turbo/ }).click();
  let body = await page.evaluate(() => buildRequest());
  check(body.steps === 6 && body.sigmas.length === 6 && body.shift_terminal === false, "Viggle 排程");
  await page.getByRole("checkbox", { name: /turbo8_lora/ }).click();
  await page.getByRole("checkbox", { name: /zzz_chibi/ }).click();
  body = await page.evaluate(() => buildRequest());
  check(body.steps === 8 && !body.sigmas && body.loras.length === 2, "加速互斥與畫風疊加");
  await page.getByRole("button", { name: "自訂", exact: true }).click();
  await page.locator("#width").fill("720");
  await page.locator("#height").fill("1280");
  const badSize = await page.evaluate(async () => { try { await buildRequest(); return false; } catch { return true; } });
  check(badSize, "720 寬度須阻擋");
  await page.locator("#width").fill("736");
  await page.locator("#height").fill("1312");
  await page.locator("#image-task").selectOption("transparent");
  body = await page.evaluate(() => buildRequest());
  check(body.size === "736x1312" && body.prompt.includes("RGBA"), "透明圖任務與自訂尺寸");
  await page.locator("#image-task").selectOption("extract");
  check(await page.evaluate(async () => { try { await buildRequest(); return false; } catch { return true; } }), "去背需原圖");
  await page.locator("#image-task").selectOption("mask");
  await page.locator("#ref-input").setInputFiles(fixture);
  await page.waitForFunction(() => state.refs.length === 1);
  check(await page.evaluate(async () => { try { await buildRequest(); return false; } catch { return true; } }), "遮罩需兩張圖");
  await page.locator("#ref-input").setInputFiles({ ...fixture, name: "mask.png" });
  await page.waitForFunction(() => state.refs.length === 2);
  body = await page.evaluate(() => buildRequest());
  check(body.images.length === 2 && body.prompt.includes("Picture 2 is a mask"), "局部修改素材");
  await page.locator("#image-task").selectOption("generate");
  await page.getByText("模型檔與量化版本", { exact: true }).click();
  await page.locator('#model-files select[data-role="dit"]').selectOption("qwen_image_2.1-Q4_K.gguf");
  body = await page.evaluate(() => buildRequest());
  check(body.model_files.dit === "qwen_image_2.1-Q4_K.gguf", "模型檔選擇送出");
  await page.locator("#mode-video").click();
  await page.locator("#steps").fill("1");
  check(await page.evaluate(async () => { try { await buildRequest(); return false; } catch { return true; } }), "影片至少兩個取樣點");
  check(await page.locator("#loras input[type=checkbox]").count() === 2, "FL2VA LoRA 篩選");
  await page.getByRole("checkbox", { name: /8step/ }).click();
  await page.locator("#duration").fill("10");
  body = await page.evaluate(() => buildRequest());
  check(body.steps === 9 && body.video_shift === 6 && body.num_frames === 240, "影片秒數與加速排程");
  check((await page.locator("#duration-help").innerText()).includes("243"), "顯示實際對齊幀數");
  await page.locator("#first-frame").setInputFiles(fixture);
  await page.locator("#video-task").selectOption("reference");
  await page.getByRole("checkbox", { name: /ref2v/ }).click();
  await page.locator("#vref-input").setInputFiles(fixture);
  await page.waitForFunction(() => state.vrefs.length === 1);
  await page.getByText("參考素材設定", { exact: true }).click();
  await page.locator("#ref-edge").fill("512");
  await page.locator("#ref-native").check();
  body = await page.evaluate(() => buildRequest());
  check(body.video_shift === 12 && body.references.length === 1 && !body.first_frame && body.ref_image_short_edge === 512 && body.ref_native_canvas, "Ref2VA 參數與首幀互斥");
  await page.getByRole("button", { name: "API／硬體", exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll("#gpus .gpu-row").length === 2);
  check((await page.locator("#host-metrics").innerText()).includes("GiB"), "主機監控資料");
  check(await page.locator("#monitor").isVisible(), "硬體監控顯示");
  await page.locator("#model-toggle").click();
  check(await page.locator("#manage-model").isVisible(), "頂部模型管理展開");
  check(await page.evaluate(() => document.querySelector("#model-toggle").parentElement.contains(document.querySelector("#connection"))), "模型管理與 API 連線同列");
  await page.getByRole("button", {name:"關閉模型管理"}).click();
  check(!await page.locator("#manage-model").isVisible(), "模型管理收起");
  check((await page.locator("#lan-help").innerText()).includes("API Base URL"), "其他電腦連線說明");
  check(await page.locator("#network-urls button").count() > 0, "區網 API 複製按鈕");
  check(await page.evaluate(() => getComputedStyle(document.querySelector(".utility-columns")).gridTemplateColumns.split(" ").length === 2), "桌面左右兩欄");
  check((await page.locator("#network-state").innerText()).length > 0, "網路存取狀態");
  await page.getByRole("button", { name: "API／硬體", exact: true }).click();
  await page.locator("#request-section > summary").click();
  check((await page.locator("#request-preview").innerText()).includes("ref_image_short_edge"), "API 預覽");
  await page.setViewportSize({ width: 390, height: 844 });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "手機 API 橫向溢出");
  await page.screenshot({ path: "out/qa/dashboard-api-mobile.png", fullPage: true });
  await page.getByRole("button", { name: "創作", exact: true }).click();
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "手機創作橫向溢出");
  await page.screenshot({ path: "out/qa/dashboard-studio-mobile.png", fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  for (const colorScheme of ["light", "dark"]) {
    await page.emulateMedia({ colorScheme, reducedMotion: "reduce" });
    await page.locator("#generate").hover();
    const contrast = await page.evaluate(() => {
      const style = getComputedStyle(document.getElementById("generate"));
      const canvas = document.createElement("canvas"), ctx = canvas.getContext("2d");
      const luminance = (color) => {
        ctx.fillStyle = color; ctx.fillRect(0, 0, 1, 1);
        const rgb = Array.from(ctx.getImageData(0, 0, 1, 1).data).slice(0, 3).map((v) => v / 255).map((v) => v <= .04045 ? v / 12.92 : ((v + .055) / 1.055) ** 2.4);
        return rgb[0] * .2126 + rgb[1] * .7152 + rgb[2] * .0722;
      };
      const a = luminance(style.color), b = luminance(style.backgroundColor);
      return (Math.max(a, b) + .05) / (Math.min(a, b) + .05);
    });
    check(contrast >= 4.5, colorScheme + " 生成按鈕滑鼠移入後對比不足");
  }
  await page.emulateMedia({ colorScheme: "light" });
  await page.getByRole("button", { name: "API／硬體", exact: true }).click();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: "out/qa/dashboard-monitor.png", fullPage: true });
  await page.emulateMedia({ colorScheme: "dark", reducedMotion: "reduce" });
  await page.screenshot({ path: "out/qa/dashboard-monitor-dark.png", fullPage: true });
  await page.emulateMedia({ colorScheme: "light" });
  await page.getByRole("button", { name: "創作", exact: true }).click();
  await page.reload();
  await page.waitForFunction(() => state.models.length === 2);
  page.off("pageerror", onError);
  check(!errors.length, "JavaScript 錯誤：" + errors.join("; "));
  return { passed: true, checks };
}
